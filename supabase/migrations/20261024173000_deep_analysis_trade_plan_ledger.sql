-- Deep market analysis + trade-plan research ledger.
-- Plans are immutable point-in-time hypotheses. Outcomes are evaluated only
-- from bars observed after plan creation; no future data is allowed at creation.

create table if not exists public.trade_plan_snapshots (
  id bigint generated by default as identity primary key,
  snapshot_id bigint references public.options_flow_snapshots(id) on delete set null,
  instrument text not null,
  contract text,
  observed_at timestamptz not null,
  plan_version text not null,
  route text not null,
  side text not null,
  status text not null default 'VALID',
  entry numeric,
  stop_loss numeric,
  tp1 numeric,
  tp2 numeric,
  tp3 numeric,
  tp4 numeric,
  tp5 numeric,
  structural_bias text,
  regime text,
  evidence_refs jsonb not null default '[]'::jsonb,
  plan_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(instrument, observed_at, plan_version, route)
);

create index if not exists trade_plan_snapshots_time_idx
  on public.trade_plan_snapshots(instrument, observed_at desc);

create index if not exists trade_plan_snapshots_route_idx
  on public.trade_plan_snapshots(instrument, route, observed_at desc);

create table if not exists public.trade_plan_outcomes (
  id bigint generated by default as identity primary key,
  plan_id bigint not null references public.trade_plan_snapshots(id) on delete cascade,
  horizon_seconds integer not null,
  observed_at timestamptz,
  entry_touched boolean,
  entry_time timestamptz,
  stop_hit boolean,
  stop_time timestamptz,
  tp1_hit boolean,
  tp1_time timestamptz,
  tp2_hit boolean,
  tp2_time timestamptz,
  tp3_hit boolean,
  tp3_time timestamptz,
  tp4_hit boolean,
  tp4_time timestamptz,
  tp5_hit boolean,
  tp5_time timestamptz,
  first_exit text,
  forward_return numeric,
  mfe numeric,
  mae numeric,
  bars_observed integer,
  outcome_state text not null default 'PENDING',
  metrics jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(plan_id, horizon_seconds)
);

create index if not exists trade_plan_outcomes_plan_idx
  on public.trade_plan_outcomes(plan_id, horizon_seconds);

alter table public.trade_plan_snapshots enable row level security;
alter table public.trade_plan_outcomes enable row level security;

drop policy if exists trade_plan_snapshots_service_role on public.trade_plan_snapshots;
create policy trade_plan_snapshots_service_role
  on public.trade_plan_snapshots
  for all to service_role
  using (true) with check (true);

drop policy if exists trade_plan_outcomes_service_role on public.trade_plan_outcomes;
create policy trade_plan_outcomes_service_role
  on public.trade_plan_outcomes
  for all to service_role
  using (true) with check (true);
