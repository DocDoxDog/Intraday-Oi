create table if not exists public.research_evidence_runs (
  id bigint generated by default as identity primary key,
  run_id text not null unique,
  strategy_id text not null,
  strategy_version text not null,
  dataset_start timestamptz,
  dataset_end timestamptz,
  oos_start timestamptz,
  oos_end timestamptz,
  oos_trades integer not null default 0,
  oos_months numeric,
  win_rate numeric,
  profit_factor numeric,
  sharpe numeric,
  psr numeric,
  dsr numeric,
  pbo numeric,
  max_drawdown_r numeric,
  cost_degradation_r numeric,
  pit_failure_rate numeric,
  status text not null default 'RESEARCH_ONLY',
  policy jsonb not null default '{}'::jsonb,
  metrics jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.paper_execution_runs (
  id bigint generated by default as identity primary key,
  run_id text not null unique,
  mode text not null default 'PAPER',
  started_at timestamptz not null,
  ended_at timestamptz,
  symbol text not null,
  trades integer not null default 0,
  fills integer not null default 0,
  rejected integer not null default 0,
  realized_r numeric not null default 0,
  spread_cost_r numeric not null default 0,
  slippage_cost_r numeric not null default 0,
  latency_ms_p50 numeric,
  latency_ms_p95 numeric,
  max_drawdown_r numeric,
  metrics jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.paper_execution_events (
  id bigint generated by default as identity primary key,
  run_id text not null,
  event_time timestamptz not null,
  event_type text not null,
  order_id text,
  symbol text,
  side text,
  quantity numeric,
  requested_price numeric,
  fill_price numeric,
  spread_cost numeric,
  slippage_cost numeric,
  latency_ms integer,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_research_evidence_strategy_created
  on public.research_evidence_runs(strategy_id, created_at desc);

create index if not exists idx_paper_execution_events_run_time
  on public.paper_execution_events(run_id, event_time);

create table if not exists public.trade_plan_journal (
  id bigint generated by default as identity primary key,
  plan_id uuid not null unique,
  snapshot_id bigint,
  run_id text not null,
  instrument text not null,
  as_of timestamptz,
  cfd_price numeric,
  futures_price numeric,
  market_bias text,
  market_regime text,
  analysis_status text,
  route text,
  side text,
  state text,
  entry numeric,
  stop numeric,
  targets jsonb not null default '[]'::jsonb,
  confidence numeric,
  risk jsonb not null default '{}'::jsonb,
  evidence_refs jsonb not null default '[]'::jsonb,
  status text not null default 'OPEN',
  entry_hit_at timestamptz,
  sl_hit_at timestamptz,
  tp1_hit_at timestamptz,
  tp2_hit_at timestamptz,
  tp3_hit_at timestamptz,
  mfe numeric,
  mae numeric,
  outcome_snapshot jsonb not null default '{}'::jsonb,
  evaluated_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_trade_plan_journal_run_asof
  on public.trade_plan_journal(run_id, as_of desc);

create index if not exists idx_trade_plan_journal_status
  on public.trade_plan_journal(status, created_at desc);

