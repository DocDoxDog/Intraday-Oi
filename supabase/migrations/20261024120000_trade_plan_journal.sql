-- Immutable trade-plan journal for later accuracy evaluation.
create table if not exists public.trade_plan_journal (
 id bigint generated by default as identity primary key,
 plan_id uuid not null unique,
 snapshot_id bigint references public.options_flow_snapshots(id) on delete set null,
 run_id text not null,
 instrument text not null,
 as_of timestamptz not null,
 cfd_price numeric,
 futures_price numeric,
 market_bias text,
 market_regime text,
 analysis_status text,
 route text not null,
 side text,
 state_at_creation text,
 entry numeric not null,
 stop numeric not null,
 targets jsonb not null default '[]'::jsonb,
 confidence numeric,
 risk_snapshot jsonb not null default '{}'::jsonb,
 evidence_refs jsonb not null default '[]'::jsonb,
 evidence_snapshot jsonb not null default '{}'::jsonb,
 status text not null default 'OPEN',
 entry_hit_at timestamptz,
 sl_hit_at timestamptz,
 tp1_hit_at timestamptz,
 tp2_hit_at timestamptz,
 tp3_hit_at timestamptz,
 mfe numeric,
 mae numeric,
 outcome_snapshot jsonb not null default '{}'::jsonb,
 evaluated_at timestamptz,
 created_at timestamptz not null default now()
);
create index if not exists trade_plan_journal_time_idx on public.trade_plan_journal(instrument,as_of desc);
create index if not exists trade_plan_journal_status_idx on public.trade_plan_journal(status,instrument,as_of desc);
alter table public.trade_plan_journal enable row level security;
revoke all on table public.trade_plan_journal from anon, authenticated;
grant select,insert,update,delete on table public.trade_plan_journal to service_role;